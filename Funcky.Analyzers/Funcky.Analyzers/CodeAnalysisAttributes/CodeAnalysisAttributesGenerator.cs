using System.Collections.Immutable;
using Microsoft.CodeAnalysis;

namespace Funcky.Analyzers.CodeAnalysisAttributes;

/// <summary>Emits the attributes that Funcky's analyzers look for into the user's own assembly, so that they can be used on
/// their own members. The attributes are opt-in through the MSBuild property <c>FunckyCodeAnalysisAttributes</c>, a list of
/// attribute names without the <c>Attribute</c> suffix, because a project that already has its own copy would otherwise get a duplicate.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class CodeAnalysisAttributesGenerator : IIncrementalGenerator
{
    /// <summary>The property the user sets. The package targets hand it to the generator as <c>_FunckyCodeAnalysisAttributes</c>,
    /// comma-separated, because a semicolon starts a comment in the .editorconfig that carries properties to the compiler.</summary>
    public const string PropertyName = "FunckyCodeAnalysisAttributes";

    public const string BuildPropertyKey = $"build_property._{PropertyName}";

    // The templates deliberately have no #nullable directive: it is an error (CS8370) in C# 7.3, which .NET Framework projects
    // use by default, and the attributes have no members that would need annotations. Gate it on the language version if one ever does.
    private const string UseWithArgumentNamesSource =
        """
        // <auto-generated/>
        namespace Funcky.CodeAnalysis
        {
            /// <summary>Methods annotated with this attribute should be called with named arguments. Funcky.Analyzers reports λ1003 otherwise.</summary>
            [global::System.AttributeUsage(global::System.AttributeTargets.Method)]
            internal sealed class UseWithArgumentNamesAttribute : global::System.Attribute
            {
            }
        }

        """;

    private const string NonDefaultableSource =
        """
        // <auto-generated/>
        namespace Funcky.CodeAnalysis
        {
            /// <summary>Structs annotated with this attribute should not be instantiated with <see langword="default"/>. Funcky.Analyzers reports λ1009 otherwise.</summary>
            [global::System.AttributeUsage(global::System.AttributeTargets.Struct)]
            internal sealed class NonDefaultableAttribute : global::System.Attribute
            {
            }
        }

        """;

    private static readonly char[] Separators = [';', ','];

    public static ImmutableDictionary<string, string> Attributes { get; } = ImmutableDictionary.CreateRange(
        StringComparer.Ordinal,
        [
            new KeyValuePair<string, string>("UseWithArgumentNames", UseWithArgumentNamesSource),
            new KeyValuePair<string, string>("NonDefaultable", NonDefaultableSource),
        ]);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var requestedAttributes = context.AnalyzerConfigOptionsProvider
            .Select(static (provider, _) => provider.GlobalOptions.TryGetValue(BuildPropertyKey, out var value) ? value : string.Empty)
            .SelectMany(static (value, _) => ParseAttributeNames(value));

        context.RegisterSourceOutput(requestedAttributes, static (context, attributeName) =>
        {
            if (Attributes.TryGetValue(attributeName, out var source))
            {
                context.AddSource($"Funcky.CodeAnalysis.{attributeName}Attribute.g.cs", source);
            }
        });
    }

    /// <summary>Unknown names are ignored here; the package's <c>.targets</c> warns about them at build time.</summary>
    public static ImmutableArray<string> ParseAttributeNames(string value)
        => value
            .Split(Separators, StringSplitOptions.RemoveEmptyEntries)
            .Select(static name => name.Trim())
            .Where(static name => name.Length > 0)
            .Distinct(StringComparer.Ordinal)
            .ToImmutableArray();
}
